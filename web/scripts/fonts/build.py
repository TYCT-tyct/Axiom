"""Subsets the product's fonts to the characters its pages show (web/README.md「字体」).

Reads sources.json, downloads each source font once into ~/.cache/axiom-fonts (under XDG_CACHE_HOME when set) and
refuses one whose SHA-256 differs, asks text.ts which characters each face must cover on each page, and writes into
packages/ui/src/css/fonts/ the woff2 files, fonts.json (what font-budget.ts and coverage.test.ts read) and coverage.txt;
it rewrites the @font-face rules at the end of packages/ui/src/css/fonts.css. A face marked "split" is cut into disjoint slices by the set of pages that show
each character, so a page loads exactly the slices holding its characters and no slice twice. The output depends only
on the inputs: timestamps are not recomputed and slices are named by their pages, so a rerun is byte for byte the same.

Run it through `pnpm fonts`, which installs requirements.txt into a virtual environment first.
"""

import hashlib
import json
import os
import shutil
import subprocess
import sys
import urllib.request
from pathlib import Path

from fontTools.subset import Options, Subsetter
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

HERE = Path(__file__).resolve().parent
WEB = HERE.parent.parent
CSS = WEB / "packages/ui/src/css"
OUT = CSS / "fonts"
CACHE = Path(os.environ.get("XDG_CACHE_HOME") or Path.home() / ".cache") / "axiom-fonts"
INPUTS = ("sources.json", "build.py", "requirements.txt")
MARKER = "/* Generated by web/scripts/fonts/build.py from sources.json: do not edit below this line. */\n"


def source_path(name, source):
    path = CACHE / f"{source['sha256']}-{name}"
    if not path.exists():
        CACHE.mkdir(parents=True, exist_ok=True)
        part = path.with_suffix(".part")
        with urllib.request.urlopen(source["url"]) as response, part.open("wb") as out:
            shutil.copyfileobj(response, out)
        part.rename(path)
    digest = hashlib.sha256(path.read_bytes()).hexdigest()
    if digest != source["sha256"]:
        path.unlink()
        sys.exit(f"{source['url']}: SHA-256 is {digest}, sources.json says {source['sha256']}")
    return path


def subset(path, axes, chars, out):
    font = TTFont(path, recalcTimestamp=False)
    options = Options()
    # Keep the hinting: without it Chromium on Linux and Windows draws Instrument Sans with uneven spacing at the
    # product's 12-14px ("Offic ial", "20.0 0"). It adds 0.03 kB to Instrument Sans, 2.2 kB to the italic.
    options.desubroutinize = True
    options.layout_features += ["tnum"]
    subsetter = Subsetter(options)
    subsetter.populate(unicodes=[ord(c) for c in chars])
    subsetter.subset(font)
    # Instancing after subsetting touches only the kept glyphs, which is what makes the Chinese faces quick.
    if axes:
        font = instantiateVariableFont(
            font, {tag: tuple(v) if isinstance(v, list) else v for tag, v in axes.items()}, inplace=True
        )
    font.flavor = "woff2"
    font.save(out, reorderTables=True)


def slices(face, texts):
    """The face's files as (pages, characters): one file, or with "split" one per set of pages sharing characters."""
    if not face.get("split"):
        return [(face["pages"], "".join(sorted(set("".join(texts.values())))))]
    owners = {}
    for page in face["pages"]:
        for char in texts[page]:
            owners.setdefault(char, []).append(page)
    groups = {}
    for char, pages in sorted(owners.items()):
        groups.setdefault(tuple(pages), []).append(char)
    return [(list(pages), "".join(chars)) for pages, chars in sorted(groups.items())]


def ranges(chars):
    points = sorted(ord(c) for c in chars)
    out, start = [], None
    for i, point in enumerate(points):
        start = point if start is None else start
        if i + 1 == len(points) or points[i + 1] != point + 1:
            out.append(f"U+{start:X}" if start == point else f"U+{start:X}-{point:X}")
            start = None
    return ",".join(out)


def slug(text):
    return "".join(c if c.isalnum() else "-" for c in text.lower()).strip("-")


def font_face(face, file, chars):
    rules = [
        f'font-family: "{face["family"]}"',
        f"font-style: {face.get('style', 'normal')}",
        f"font-weight: {face['weight']}",
        "font-display: swap",
        f'src: url("./fonts/{file}") format("woff2")',
        f"unicode-range: {ranges(chars)}",
        *(f"{k}: {v}" for k, v in face.get("descriptors", {}).items()),
    ]
    return "@font-face {\n" + "".join(f"  {rule};\n" for rule in rules) + "}\n"


def inputs_fingerprint():
    """What the output was cut from: the manifest, this script and its tools (coverage.test.ts computes the same)."""
    lines = (f"{name} {hashlib.sha256((HERE / name).read_bytes()).hexdigest()}\n" for name in INPUTS)
    return hashlib.sha256("".join(lines).encode()).hexdigest()


def main():
    manifest = json.loads((HERE / "sources.json").read_text())
    texts = json.loads(subprocess.run(["node", str(HERE / "text.ts")], check=True, capture_output=True, cwd=WEB).stdout)
    if OUT.exists():
        shutil.rmtree(OUT)
    OUT.mkdir(parents=True)

    faces, css, report = [], [], []
    for face, per_page in zip(manifest["faces"], texts, strict=True):
        path = source_path(face["source"], manifest["sources"][face["source"]])
        cmap = TTFont(path, lazy=True)["cmap"].getBestCmap()
        wanted = set("".join(per_page.values()))
        absent = "".join(sorted(c for c in wanted if ord(c) not in cmap))
        present = {page: "".join(c for c in chars if ord(c) in cmap) for page, chars in per_page.items()}
        name = "-".join(filter(None, [slug(face["family"]), slug(face["weight"]), face.get("style")]))
        files = []
        for pages, chars in slices(face, present):
            if not chars:
                continue
            file = f"{name}.{'_'.join(slug(p) for p in pages)}.woff2" if face.get("split") else f"{name}.woff2"
            subset(path, face.get("axes"), chars, OUT / file)
            data = (OUT / file).read_bytes()
            files.append(
                {
                    "file": file,
                    "pages": pages,
                    "bytes": len(data),
                    "sha256": hashlib.sha256(data).hexdigest(),
                    "chars": chars,
                }
            )
            css.append(font_face(face, file, chars))
        script = face["text"].get("script", "latin")
        faces.append({k: face[k] for k in ("family", "weight", "pages")} | {"style": face.get("style", "normal"),
                     "script": script, "absent": absent, "files": files})
        for page in face["pages"]:
            loads = [f for f in files if page in f["pages"]]
            report.append(
                f"{page:12} {face['family']} {face['weight']} {face.get('style', 'normal')}: "
                f"{len(present[page])} chars in {len(loads)} files, {sum(f['bytes'] for f in loads)} bytes"
                + (f"; not in the font: {absent}" if absent else "")
            )

    (OUT / "fonts.json").write_text(json.dumps({"inputs": inputs_fingerprint(), "faces": faces}, ensure_ascii=False, indent=1) + "\n")
    (OUT / "coverage.txt").write_text("".join(f"{line}\n" for line in sorted(report)))
    fonts_css = CSS / "fonts.css"
    hand_written = fonts_css.read_text().split(MARKER)[0]
    fonts_css.write_text(hand_written + MARKER + "\n".join(css))
    # In the repository's format, so `pnpm lint` passes on the output as written.
    subprocess.run(["pnpm", "exec", "biome", "format", "--write", OUT / "fonts.json", fonts_css], check=True, cwd=WEB)


if __name__ == "__main__":
    main()
