"""Subsets the product's fonts to the characters its pages show (web/README.md「字体」).

Reads sources.json, downloads each source font once into ~/.cache/axiom-fonts (under XDG_CACHE_HOME when set) and
refuses one whose SHA-256 differs, asks text.ts which characters each face must cover on each page, and writes into
packages/ui/src/css/fonts/ the woff2 files, fonts.json (what font-budget.ts, coverage.test.ts and the build's preload
read) and coverage.txt; it rewrites the @font-face rules at the end of packages/ui/src/css/fonts.css. A face marked
"split" is cut into disjoint slices, so a page loads exactly the slices holding its characters and no slice twice
(slices). The output depends only on the inputs: timestamps are not recomputed, slices are named by their pages and the
merge breaks ties by order, so a rerun is byte for byte the same.

Run it through `pnpm fonts`, which installs requirements.txt into a virtual environment first.
"""

import hashlib
import heapq
import io
import json
import os
import shutil
import subprocess
import sys
import urllib.request
import zipfile
from pathlib import Path

from fontTools.subset import Options, Subsetter
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

HERE = Path(__file__).resolve().parent
WEB = HERE.parent.parent
CSS = WEB / "packages/ui/src/css"
OUT = CSS / "fonts"
CACHE = Path(os.environ.get("XDG_CACHE_HOME") or Path.home() / ".cache") / "axiom-fonts"
INPUTS = ("sources.json", "build.py", "text.ts", "routes.ts", "requirements.txt")
# What one more file costs a page beyond its glyphs, in bytes: a woff2 file's own tables (measured per face, about
# 0.5 kB for MiSans) plus this for its request, the headers both ways and one more fetch to schedule. Without it the
# merge leaves the admin's face at 101 kB, over the page budget its worst case is held to (slices).
REQUEST_BYTES = 1000
MARKER = "/* Generated by web/scripts/fonts/build.py from sources.json: do not edit below this line. */\n"


def source_path(name, source):
    """The source font's file: the download itself, or the member it names when the download is an archive."""
    path = CACHE / f"{source['sha256']}-{name}"
    if not path.exists():
        CACHE.mkdir(parents=True, exist_ok=True)
        part = path.with_suffix(".part")
        with urllib.request.urlopen(source["url"]) as response, part.open("wb") as out:
            shutil.copyfileobj(response, out)
        part.rename(path)
    digest = hashlib.sha256(path.read_bytes()).hexdigest()
    if digest != source["sha256"]:
        path.unlink()
        sys.exit(f"{source['url']}: SHA-256 is {digest}, sources.json says {source['sha256']}")
    if "member" not in source:
        return path
    member = path.with_name(f"{path.name}.{Path(source['member']).suffix.lstrip('.')}")
    if not member.exists():
        # MiSans.zip stores its names in UTF-8 without the flag that says so, which Python would read as CP437.
        with zipfile.ZipFile(path, metadata_encoding="utf-8") as archive:
            member.write_bytes(archive.read(source["member"]))
    return member


def subset(path, axes, chars, out):
    font = TTFont(path, recalcTimestamp=False)
    options = Options()
    # Keep the hinting: without it Chromium on Linux and Windows draws Instrument Sans with uneven spacing at the
    # product's 12-14px ("Offic ial", "20.0 0"). It adds 0.03 kB to Instrument Sans, 2.2 kB to the italic.
    options.desubroutinize = True
    options.layout_features += ["tnum"]
    subsetter = Subsetter(options)
    subsetter.populate(unicodes=[ord(c) for c in chars])
    subsetter.subset(font)
    # Instancing after subsetting touches only the kept glyphs, which is what makes the Chinese faces quick.
    if axes:
        font = instantiateVariableFont(
            font, {tag: tuple(v) if isinstance(v, list) else v for tag, v in axes.items()}, inplace=True
        )
    font.flavor = "woff2"
    font.save(out, reorderTables=True)


def woff2_size(path, axes, chars):
    out = io.BytesIO()
    subset(path, axes, chars, out)
    return len(out.getvalue())


def slices(face, texts, path):
    """The face's files as (pages, characters): one file, or with "split" disjoint slices that a page loads only when it
    shows one of their characters (unicode-range).

    The exact cut, one slice per set of pages sharing characters, gives every page only its own characters but splinters
    into hundreds of one-character files once forty pages share a shell. So slices are merged, cheapest first, while a
    merge lowers what all pages load together, every page counting the same: merging two slices saves each page that
    loads both one file's cost, and makes each page that loads only one of them load the other's characters too. Each
    page also counts its worst case, every slice of the face: text from the API (a workspace's name) can hold any
    character and unicode-range loads the slice that has it, so merging two slices also saves every page one file's
    own tables in its worst case, which the budget holds (font-budget.ts)."""
    pages = list(texts)
    if not face.get("split"):
        return [(pages, "".join(sorted(set("".join(texts.values())))))]
    owners = {}
    for page in pages:
        for char in texts[page]:
            owners.setdefault(char, []).append(page)
    groups = {}
    for char, owned in sorted(owners.items()):
        groups.setdefault(tuple(owned), []).append(char)
    cut = [(frozenset(owned), "".join(chars)) for owned, chars in sorted(groups.items())]
    live = dict(enumerate(cut))
    if len(cut) > 1:
        every = "".join(chars for _, chars in cut)
        one = woff2_size(path, face.get("axes"), every[0])
        per_char = (woff2_size(path, face.get("axes"), every) - one) / (len(every) - 1)
        per_file = one + REQUEST_BYTES

        def cost(a, b):
            (pa, ca), (pb, cb) = a, b
            return per_char * (len(ca) * len(pb - pa) + len(cb) * len(pa - pb)) - per_file * len(pa & pb) - one * len(pages)

        heap = [(cost(live[i], live[j]), i, j) for i in live for j in live if i < j]
        heapq.heapify(heap)
        while heap and heap[0][0] < 0:
            _, i, j = heapq.heappop(heap)
            if i in live and j in live:
                merged = (live[i][0] | live[j][0], "".join(sorted(live.pop(i)[1] + live.pop(j)[1])))
                for k, other in live.items():
                    heapq.heappush(heap, (cost(other, merged), k, len(cut)))
                live[len(cut)] = merged
                cut.append(merged)
    return sorted((sorted(owned, key=pages.index), chars) for owned, chars in live.values())


def ranges(chars):
    points = sorted(ord(c) for c in chars)
    out, start = [], None
    for i, point in enumerate(points):
        start = point if start is None else start
        if i + 1 == len(points) or points[i + 1] != point + 1:
            out.append(f"U+{start:X}" if start == point else f"U+{start:X}-{point:X}")
            start = None
    return ",".join(out)


def slug(text):
    return "".join(c if c.isalnum() else "-" for c in text.lower()).strip("-")


def font_face(face, file, chars):
    rules = [
        f'font-family: "{face["family"]}"',
        f"font-style: {face.get('style', 'normal')}",
        f"font-weight: {face['weight']}",
        "font-display: swap",
        f'src: url("./fonts/{file}") format("woff2")',
        f"unicode-range: {ranges(chars)}",
        *(f"{k}: {v}" for k, v in face.get("descriptors", {}).items()),
    ]
    return "@font-face {\n" + "".join(f"  {rule};\n" for rule in rules) + "}\n"


def fallback_face(fallback, path):
    """The face a page shows while the source's slices load: fonts visitors have (local), given the source's line
    metrics so the swap moves no line. Chinese glyphs are one em wide in every font it names, so the advance needs no
    adjusting; the ascent and descent do (MiSans 1.044 and 0.282 em, Noto Sans CJK 1.16 and 0.288), since with them a
    line's glyph boxes sit differently around the baseline and the line box grows."""
    font = TTFont(path, lazy=True)
    em, hhea, os2 = font["head"].unitsPerEm, font["hhea"], font["OS/2"]
    # Windows lays the font out by its win metrics, the others by hhea: one override fits all only when they agree.
    if (os2.usWinAscent, os2.usWinDescent) != (hhea.ascent, -hhea.descent) or hhea.lineGap:
        sys.exit(f"{fallback['family']}: hhea and OS/2 win metrics differ; one override cannot match both")
    advance = font["hmtx"][font.getBestCmap()[0x4E00]][0]
    rules = [
        f'font-family: "{fallback["family"]}"',
        "src: " + ", ".join(f'local("{name}")' for name in fallback["local"]),
        f"unicode-range: {fallback['unicode-range']}",
        f"size-adjust: {advance / em:.2%}",
        f"ascent-override: {hhea.ascent / em:.2%}",
        f"descent-override: {-hhea.descent / em:.2%}",
        "line-gap-override: 0%",
    ]
    return "@font-face {\n" + "".join(f"  {rule};\n" for rule in rules) + "}\n"


def inputs_fingerprint():
    """What the output was cut from: the manifest, the scripts and their tools (coverage.test.ts computes the same)."""
    lines = (f"{name} {hashlib.sha256((HERE / name).read_bytes()).hexdigest()}\n" for name in INPUTS)
    return hashlib.sha256("".join(lines).encode()).hexdigest()


def main():
    manifest = json.loads((HERE / "sources.json").read_text())
    texts = json.loads(subprocess.run(["node", str(HERE / "text.ts")], check=True, capture_output=True, cwd=WEB).stdout)
    # The rest of the directory (the MiSans licence) is not the pipeline's to remove.
    OUT.mkdir(parents=True, exist_ok=True)
    for old in OUT.glob("*.woff2"):
        old.unlink()

    faces, css, report = [], [], []
    for face, per_page in zip(manifest["faces"], texts, strict=True):
        path = source_path(face["source"], manifest["sources"][face["source"]])
        cmap = TTFont(path, lazy=True)["cmap"].getBestCmap()
        wanted = set("".join(per_page.values()))
        absent = "".join(sorted(c for c in wanted if ord(c) not in cmap))
        present = {page: "".join(c for c in chars if ord(c) in cmap) for page, chars in per_page.items()}
        name = "-".join(filter(None, [slug(face["family"]), slug(face["weight"]), face.get("style")]))
        files = []
        for pages, chars in slices(face, present, path):
            if not chars:
                continue
            # A slice is named by its pages, which can be forty: the name carries their digest, fonts.json the list.
            digest = hashlib.sha256(",".join(pages).encode()).hexdigest()[:8]
            file = f"{name}.{digest}.woff2" if face.get("split") else f"{name}.woff2"
            subset(path, face.get("axes"), chars, OUT / file)
            data = (OUT / file).read_bytes()
            files.append(
                {
                    "file": file,
                    "pages": pages,
                    "bytes": len(data),
                    "sha256": hashlib.sha256(data).hexdigest(),
                    "chars": chars,
                }
                | ({"preload": True} if set(pages) & set(face.get("preload", [])) else {})
            )
            css.append(font_face(face, file, chars))
        script = face["text"].get("script", "latin")
        faces.append({k: face[k] for k in ("family", "weight")} | {"pages": list(per_page), "style": face.get("style", "normal"),
                     "script": script, "absent": absent, "files": files})
        for page in per_page:
            loads = [f for f in files if page in f["pages"]]
            report.append(
                f"{page:28} {face['family']} {face['weight']} {face.get('style', 'normal')}: "
                f"{len(present[page])} chars in {len(loads)} files, {sum(f['bytes'] for f in loads)} bytes"
                + (f"; not in the font: {absent}" if absent else "")
            )

    (OUT / "fonts.json").write_text(json.dumps({"inputs": inputs_fingerprint(), "faces": faces}, ensure_ascii=False, indent=1) + "\n")
    (OUT / "coverage.txt").write_text("".join(f"{line}\n" for line in sorted(report)))
    fonts_css = CSS / "fonts.css"
    hand_written = fonts_css.read_text().split(MARKER)[0]
    for fallback in manifest.get("fallbacks", []):
        css.append(fallback_face(fallback, source_path(fallback["source"], manifest["sources"][fallback["source"]])))
    fonts_css.write_text(hand_written + MARKER + "\n".join(css))
    # In the repository's format, so `pnpm lint` passes on the output as written.
    subprocess.run(["pnpm", "exec", "biome", "format", "--write", OUT / "fonts.json", fonts_css], check=True, cwd=WEB)


if __name__ == "__main__":
    main()
