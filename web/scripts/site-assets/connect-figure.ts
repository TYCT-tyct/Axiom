// The connect screen's isometric figure (#747 S2c), cut from the Site board's script into what the page loads: the
// drawing as one SVG asset (fetched when the screen nears the view), and its numbers and the board's drawing kit
// (the functions its script redraws the wiper and the shaft with) as a generated module. The board's script holds all of
// it in one 500 kB line; the page must not. Run `pnpm --dir web site-assets` after the board changes and commit the
// output; `--check` says whether the committed files are current.
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const web = join(import.meta.dirname, "../..");
const source = join(web, "packages/boards/inputs/Site.logic.html");
const home = join(web, "site/src/home");
const marker = "/* @generated by pnpm site-assets; DO NOT EDIT. */";

// The two groups the board draws invisible with a style attribute, which the page's content security policy blocks:
// the loader sets that opacity itself (home/connect-script.ts, `.pulse`).
const hidden = ' style="opacity:0"';

export function cut(logic: string) {
  const lines = logic.split("\n");
  const at = lines.findIndex((line) => line.startsWith("const FIG = "));
  const figure = JSON.parse((lines[at] as string).slice("const FIG = ".length).replace(/;\s*$/, ""));
  const start = lines.findIndex((line) => line.startsWith("const K = (() => {"));
  const end = lines.findIndex((line) => line.startsWith("const PAGE_CSS"));
  if (at < 0 || start < 0 || end < start) throw new Error("the Site board's script has changed shape");
  const { svg, ...numbers } = figure as { svg: string };
  const clean = svg.replaceAll(hidden, "");
  if (svg.split(hidden).length !== 3 || clean.includes("style="))
    throw new Error("the figure's style attributes changed");
  const kit = [...lines.slice(start, end), "return { extrude, cylinder, solidSvg, lineSvg, knurl };", "})();"].join(
    "\n",
  );
  return {
    "connect-figure.svg": clean,
    "connect-figure.gen.ts": `${marker}\n// @ts-nocheck -- the board's own drawing kit, preserved as it is.\nexport const figure = ${JSON.stringify(numbers)};\nexport const kit = ${kit.replace("const K = ", "")}\n`,
  };
}

if (import.meta.main) {
  const outputs = cut(readFileSync(source, "utf8"));
  const stale = Object.entries(outputs).filter(
    ([name, text]) => !existsSync(join(home, name)) || readFileSync(join(home, name), "utf8") !== text,
  );
  if (process.argv.includes("--check")) {
    if (stale.length)
      throw new Error(`stale: ${stale.map(([name]) => name).join(", ")}; run pnpm --dir web site-assets`);
  } else {
    for (const [name, text] of stale) writeFileSync(join(home, name), text);
  }
}
