import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { pinBoard, readBoard } from "../packages/boards/source.ts";
import { csp } from "./boards/csp.ts";
import { template } from "./boards/template.ts";

export const marker = "/* @generated by pnpm boards; DO NOT EDIT. */";
const boardNames = ["Login", "ClawdEgg", "AxApp"] as const;
export const packageRoot = resolve(import.meta.dirname, "../packages/boards");
const inputRoot = join(packageRoot, "inputs");
const engineNames = ["ocean-orig", "login-ui", "clawd", "clawd-egg"];
const engines: Record<string, string[]> = {
  Login: ["ocean-orig", "login-ui"],
  ClawdEgg: ["ocean-orig", "clawd", "clawd-egg"],
  AxApp: [],
};
const header = `${marker}\n// @ts-nocheck -- mechanically preserved design JavaScript; the public props are typed.\n/* jscpd:ignore-start */\n`;

type Prop = { default?: unknown; options?: unknown[] };
function parts(html: string) {
  const helmet = html.match(/<helmet>([\s\S]*?)<\/helmet>/)?.[1];
  const markup = html.match(/<\/helmet>([\s\S]*?)<\/x-dc>/)?.[1];
  const logic = html.match(/data-dc-script[^>]*>([\s\S]*?)<\/script>/)?.[1];
  const props = JSON.parse(html.match(/data-props='([^']*)'/)?.[1] ?? "{}") as Record<string, Prop>;
  if (helmet === undefined || markup === undefined || logic === undefined) throw new Error("missing board sections");
  const css = [...helmet.matchAll(/<style[^>]*>([\s\S]*?)<\/style>/g)]
    .map((m) => m[1])
    .join("\n")
    .replace(/@font-face\s*\{[^}]*\}/g, "");
  return { css, markup, logic, props };
}

export function convert(html: string, name: string): Record<string, string> {
  const { css, markup, logic, props } = parts(html);
  const declared = Object.entries(props).filter(([, p]) => "default" in p);
  const defaults = Object.fromEntries(declared.map(([key, p]) => [key, p.default]));
  const types = declared
    .map(
      ([key, p]) =>
        `${JSON.stringify(key)}?: ${p.options ? p.options.map((v) => JSON.stringify(v)).join(" | ") : typeof p.default};`,
    )
    .join("\n");
  const imports = (engines[name] ?? []).map((engine) => `import "../engines/${engine}.js";`).join("\n");
  return {
    [`${name}/board.css`]: `${marker}\n/* jscpd:ignore-start */\n${css}\n/* jscpd:ignore-end */\n`,
    [`${name}/logic.ts`]: `${header}import { DCLogic } from "../runtime.tsx";\nimport { boardHTML, boardCSS } from "../dom.ts";\n${imports}\n${csp(logic).replace("class Component extends DCLogic", "export class Component extends DCLogic")}\n/* jscpd:ignore-end */\n`,
    [`${name}/Board.tsx`]: `${header}import { Component } from "./logic.ts";\nimport { boardStyle } from "../dom.ts";\nimport "./board.css";\ntype Props = {\n${types}\n};\nexport default class Board extends Component {\n  declare props: Props;\n  static defaultProps = ${JSON.stringify(defaults)};\n  static template = (v, bind) => <>${template(markup)}</>;\n  componentDidMount() { this.flushRefs(); super.componentDidMount?.(); }\n  componentDidUpdate(...args) { this.flushRefs(); super.componentDidUpdate?.(...args); }\n}\n/* jscpd:ignore-end */\n`,
  };
}

function outputs(input = inputRoot): Record<string, string> {
  const result: Record<string, string> = {};
  for (const name of boardNames) Object.assign(result, convert(readBoard(join(input, `${name}.dc.html`)), name));
  result["demo-fonts.css"] =
    `${marker}\n@font-face{font-family:'Axiom Sans';font-weight:400 700;size-adjust:105%;src:url('/fonts/instrument-sans')}
@font-face{font-family:'Axiom Mono';font-weight:100 800;src:url('/fonts/jetbrains-mono')}
@font-face{font-family:'Axiom CJK';font-weight:150 700;src:url('/fonts/cjk-body')}
@font-face{font-family:'AX Serif';font-weight:250 900;src:url('/fonts/cjk-serif')}
@font-face{font-family:'AX Serif Latin';font-style:italic;font-weight:400;src:url('/fonts/instrument-serif-italic')}
`;
  for (const name of engineNames)
    result[`engines/${name}.js`] =
      `${marker}\n/* jscpd:ignore-start */\n${readFileSync(join(input, `${name}.js.txt`), "utf8")}\nexport {};\n/* jscpd:ignore-end */\n`;
  return result;
}

export function generatedBoard(path: string, text: string): boolean {
  return path.startsWith("packages/boards/src/") && text.startsWith(`${marker}\n`);
}

export function checkGenerated(root = packageRoot): string[] {
  const expected = outputs(join(root, "inputs"));
  const files = readdirSync(join(root, "src"), { recursive: true }).filter((p) => typeof p === "string") as string[];
  const marked = files.filter(
    (p) => /\.(tsx?|js|css)$/.test(p) && readFileSync(join(root, "src", p), "utf8").startsWith(marker),
  );
  return [...new Set([...Object.keys(expected), ...marked])].filter(
    (p) =>
      !expected[p] || !existsSync(join(root, "src", p)) || readFileSync(join(root, "src", p), "utf8") !== expected[p],
  );
}

export function generate(root = packageRoot) {
  for (const [path, text] of Object.entries(outputs(join(root, "inputs")))) {
    const file = join(root, "src", path);
    mkdirSync(dirname(file), { recursive: true });
    writeFileSync(file, text);
  }
}

if (import.meta.main) {
  if (process.argv.includes("--check")) {
    const stale = checkGenerated();
    if (stale.length) throw new Error(`run pnpm boards; stale generated files: ${stale.join(", ")}`);
  } else {
    const design = process.env.AXIOM_DESIGN_DIR;
    if (design) {
      const source = existsSync(join(design, "project")) ? join(design, "project") : design;
      for (const name of boardNames)
        pinBoard(join(inputRoot, `${name}.dc.html`), readBoard(join(source, `${name}.dc.html`)));
      for (const name of engineNames)
        writeFileSync(join(inputRoot, `${name}.js.txt`), readFileSync(join(source, `${name}.js`)));
    }
    generate();
  }
}
