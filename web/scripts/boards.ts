export const marker = "/* @generated by pnpm boards; DO NOT EDIT. */";
const sharedSheetBoard = "AxApp";
const sharedSheetFamily = new Set(["AxApp", "AxAppTablet", "AxAppPhone", "AxAppDark", "AxAppPhoneDark"]);
const reexportFrom: Record<string, string> = { AxAppPhone: "AxApp" };
export const packageRoot = resolve(import.meta.dirname, "../packages/boards");
const inputRoot = join(packageRoot, "inputs");
const header = `${marker}\n// @ts-nocheck -- mechanically preserved design JavaScript; the public props are typed.\n/* jscpd:ignore-start */\n`;

// Every animation plays whatever the reader's system setting (docs/frontend.md「动画」), so the designer's
// reduced-motion rules, one level of rules deep, stay out of the stylesheets. The boards' own scripts reach no product
// page and keep their checks.
const reducedMotion = /@media\s*\(prefers-reduced-motion:\s*reduce\)\s*\{(?:[^{}]|\{[^{}]*\})*\}\n?/g;

// Workaround for https://github.com/TYCT-tyct/Axiom/issues/882: lightningcss 1.33.0 drops `backdrop-filter` when a
// hand-written `-webkit-backdrop-filter` follows it in the same rule, so every glass blur would be missing in Chrome and
// Firefox. The designer's prefixed copies stay out; lightningcss adds the prefix for the browser targets. Delete this
// (and its test) once the project builds with a lightningcss release that fixes parcel-bundler/lightningcss#1327.
const webkitBackdrop = /-webkit-backdrop-filter\s*:[^;}]*;?/g;

function parts(html: string) {
  const helmet = html.match(/<helmet>([\s\S]*?)<\/helmet>/)?.[1];
  const markup = html.match(/<\/helmet>([\s\S]*?)<\/x-dc>/)?.[1];
  const logic = html.match(/data-dc-script[^>]*>([\s\S]*?)<\/script>/)?.[1];
  const props = boardProps(html);
  if (helmet === undefined || markup === undefined || logic === undefined) throw new Error("missing board sections");
  const css = [...helmet.matchAll(/<style[^>]*>([\s\S]*?)<\/style>/g)]
    .map((m) => m[1])
    .join("\n")
    .replace(/@font-face\s*\{[^}]*\}/g, "")
    .replace(reducedMotion, "")
    .replace(webkitBackdrop, "");
  return { css, markup, logic, props };
}

export function convert(html: string, name: string): Record<string, string> {
  const { css, markup, logic, props } = parts(html);
  const declared = Object.entries(props).filter(([, p]) => "default" in p);
  const defaults = Object.fromEntries(declared.map(([key, p]) => [key, p.default]));
  const types = declared
    .map(
      ([key, p]) =>
        `${JSON.stringify(key)}?: ${p.options ? p.options.map((v) => JSON.stringify(v)).join(" | ") : typeof p.default};`,
    )
    .join("\n");
  const imports = boardEngines(name, html)
    .map((engine) => `import "../engines/${engine}.js";`)
    .join("\n");
  return {
    [`${name}/board.css`]: `${marker}\n/* jscpd:ignore-start */\n${css}\n/* jscpd:ignore-end */\n`,
    [`${name}/logic.ts`]: `${header}import { DCLogic } from "../runtime.tsx";\nimport { boardHTML, boardCSS } from "../dom.ts";\n${imports}\n${exportComponent(csp(logic))}\n/* jscpd:ignore-end */\n`,
    [`${name}/Board.tsx`]: `${header}import { Component } from "./logic.ts";\nimport { boardStyle } from "../dom.ts";\nimport "./board.css";\ntype Props = {\n${types}\n};\nexport default class Board extends Component {\n  declare props: Props;\n  static defaultProps = ${JSON.stringify(defaults)};\n  static template = (v, bind) => <>${template(markup)}</>;\n  componentDidMount() { this.flushRefs(); super.componentDidMount?.(); }\n  componentDidUpdate(...args) { this.flushRefs(); super.componentDidUpdate?.(...args); }\n}\n/* jscpd:ignore-end */\n`,
  };
}

function reexportLine(wide: string, file: string) {
  const target = JSON.stringify(`../../${wide}/regions/${file}`);
  if (file.endsWith(".demo.ts")) {
    const stem = file.slice(0, -".demo.ts".length);
    return `${marker}\nimport type en from "./${stem}.en.ts";\nimport type { Props } from "./${stem}.tsx";\nimport { demo as wide } from ${target};\nexport const demo: (t: (key: keyof typeof en) => string) => Props = wide;\n`;
  }
  const clause = file.endsWith(".tsx") ? "default, type Props" : "default";
  return `${marker}\nexport { ${clause} } from ${target};\n`;
}

function dedupeReexports(result: Record<string, string>, names: readonly string[]) {
  for (const [phone, wide] of Object.entries(reexportFrom)) {
    if (!names.includes(phone) || !names.includes(wide)) continue;
    const prefix = `${phone}/regions/`;
    for (const key of Object.keys(result).filter((k) => k.startsWith(prefix))) {
      const file = key.slice(prefix.length);
      if (result[`${wide}/regions/${file}`] === result[key]) result[key] = reexportLine(wide, file);
    }
  }
}

