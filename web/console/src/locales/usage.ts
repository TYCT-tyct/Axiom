export type UsageLocaleKey = keyof typeof zh;

export function usageText(language: "zh" | "en", key: UsageLocaleKey, vars?: Record<string, string | number>): string {
  const raw = (language === "en" ? en : zh)[key];
  if (!vars) return raw;
  return raw.replace(/\{\{(\w+)\}\}/g, (_, name: string) => String(vars[name] ?? ""));
}
