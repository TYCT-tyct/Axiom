// Command pendingapi writes, for a contract in api/, a type whose methods answer the operations that have no handler yet
// with errNotImplemented, so the program builds while the handlers of a new contract are written one by one.
//
// The generated interface of a contract (StrictServerInterface) has a method for every operation, so adding an
// operation to the contract would otherwise break the build until every handler exists. The type this writes is
// embedded in the handler type; a method the handler type declares takes the operation over, and the next generation
// leaves that operation out. An operation implemented by name and not yet regenerated is a duplicate method, which the
// compiler reports. Once every operation has a handler the type is empty and the embedding, the go:generate line and
// the generated file are deleted.
//
// usage: go run -C tools ./pendingapi <contract> <package dir> <output file> <api package import path> <handler type> <pending type>
package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"path"
	"path/filepath"
	"slices"
	"strings"
	"text/template"

	"github.com/getkin/kin-openapi/openapi3"
)

func main() {
	if len(os.Args) != 7 {
		fmt.Fprintln(os.Stderr, "usage: pendingapi <contract> <package dir> <output file> <api package import path> <handler type> <pending type>")
		os.Exit(2)
	}
	if err := run(os.Args[1], os.Args[2], os.Args[3], os.Args[4], os.Args[5], os.Args[6]); err != nil {
		fmt.Fprintln(os.Stderr, "pendingapi:", err)
		os.Exit(1)
	}
}

func run(contract, dir, output, apiImport, handler, pending string) error {
	doc, err := openapi3.NewLoader().LoadFromFile(contract)
	if err != nil {
		return err
	}
	done, pkg, err := implemented(dir, filepath.Base(output), handler)
	if err != nil {
		return err
	}
	var methods []string
	for _, item := range doc.Paths.Map() {
		for _, op := range item.Operations() {
			if name := strings.ToUpper(op.OperationID[:1]) + op.OperationID[1:]; !done[name] {
				methods = append(methods, name)
			}
		}
	}
	slices.Sort(methods)
	var out bytes.Buffer
	data := struct {
		Contract, Package, Import, Alias, Pending string
		Methods                                   []string
	}{filepath.ToSlash(filepath.Join("api", filepath.Base(contract))), pkg, apiImport, path.Base(apiImport), pending, methods}
	if err := tmpl.Execute(&out, data); err != nil {
		return err
	}
	src, err := format.Source(out.Bytes())
	if err != nil {
		return err
	}
	return os.WriteFile(filepath.Join(dir, filepath.Base(output)), src, 0o644) //nolint:gosec // the arguments come from a go:generate line, and a source file is meant to be read by everyone
}

// implemented returns the names of the methods the handler type declares in the package's hand-written files, and the
// package's name. The generated file itself is left out: it is what is being written again.
func implemented(dir, generated, handler string) (map[string]bool, string, error) {
	names, err := filepath.Glob(filepath.Join(dir, "*.go"))
	if err != nil {
		return nil, "", err
	}
	done := map[string]bool{}
	var pkg string
	for _, name := range names {
		if base := filepath.Base(name); base == generated || strings.HasSuffix(base, "_test.go") {
			continue
		}
		f, err := parser.ParseFile(token.NewFileSet(), name, nil, 0)
		if err != nil {
			return nil, "", err
		}
		pkg = f.Name.Name
		for _, decl := range f.Decls {
			if fn, ok := decl.(*ast.FuncDecl); ok && fn.Recv != nil && receiverName(fn.Recv.List[0].Type) == handler {
				done[fn.Name.Name] = true
			}
		}
	}
	return done, pkg, nil
}

// receiverName is the type name of a method receiver, with or without a pointer.
func receiverName(t ast.Expr) string {
	if star, ok := t.(*ast.StarExpr); ok {
		t = star.X
	}
	if id, ok := t.(*ast.Ident); ok {
		return id.Name
	}
	return ""
}

var tmpl = template.Must(template.New("pending").Parse(`// Code generated by pendingapi from {{.Contract}}. DO NOT EDIT.

package {{.Package}}

import (
	"context"

	"{{.Import}}"
)

// {{.Pending}} answers the operations of {{.Contract}} that have no handler yet.
type {{.Pending}} struct{}
{{range .Methods}}
func ({{$.Pending}}) {{.}}(context.Context, {{$.Alias}}.{{.}}RequestObject) ({{$.Alias}}.{{.}}ResponseObject, error) {
	return nil, errNotImplemented
}
{{end}}`))
