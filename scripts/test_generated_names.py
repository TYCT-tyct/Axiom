import unittest

import justrepo

HEADER = "// Code generated by hand. DO NOT EDIT.\n\npackage plant\n"


def generated_names(files, commit):
    """Run the real `just generated-names` in a fresh repository holding files ({path: content})."""
    with justrepo.repository() as repo:
        if commit:
            justrepo.commit(repo, files)
        else:
            justrepo.write(repo, files)
        return justrepo.just(repo, "generated-names")


class GeneratedNames(unittest.TestCase):
    def test_cases(self):
        cases = [
            ("a generator's name", "internal/plant/plant.gen.go", HEADER, False, False),
            ("a hand-written file with the header", "internal/plant/plant.go", HEADER, False, True),
            ("the same, committed", "internal/plant/plant.go", HEADER, True, True),
            ("the header among doc comments, as oapi-codegen writes it", "internal/plant/api.go",
             "// Package plant is generated.\n//\n// Code generated by x v1 DO NOT EDIT.\npackage plant\n", False, True),
            ("a header with Windows line ends", "internal/plant/plant.go",
             "// Code generated by hand. DO NOT EDIT.\r\n\r\npackage plant\r\n", False, True),
            ("a test file with the header", "internal/plant/plant_test.go", HEADER, False, True),
            ("a header without the do-not-edit mark", "internal/plant/plant.go",
             "// Code generated by hand.\n\npackage plant\n", False, False),
            ("a header in another case, which golangci-lint does not read", "internal/plant/plant.go",
             "// code generated by hand. do not edit.\n\npackage plant\n", False, False),
            ("the words in a trailing comment", "internal/plant/plant.go",
             "package plant\n\nvar x = 1 // Code generated by hand. DO NOT EDIT.\n", False, False),
            ("other file types", "docs/plant.md", HEADER, False, False),
        ]
        for name, path, content, commit, fails in cases:
            with self.subTest(name):
                result = generated_names({path: content}, commit)
                self.assertEqual(result.returncode != 0, fails, result.stdout)
                if fails:
                    self.assertIn(path, result.stdout)

    def test_a_git_failure_fails(self):
        self.assertNotEqual(justrepo.just_with_broken_git("generated-names").returncode, 0)


if __name__ == "__main__":
    unittest.main()
