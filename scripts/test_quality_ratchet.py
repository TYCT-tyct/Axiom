"""Tests for the quality ratchet: a fixture tree that grows a count fails, one that falls without lowering the baseline
fails too, and a package whose coverage falls, rises or starts below the floor must move the baseline. The fixture trees
are measured by tools/qualityratchet, so the tests exercise the real gocognit numbers, the coverage profile parser, the
generated/test exclusions and the baseline comparison together."""

import json
import os
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SCRIPT = ROOT / "scripts" / "ci" / "quality_ratchet.py"

ZERO = {
    "version": 2,
    "description": "fixture",
    "ceilings": {"gocognit": 30, "file_lines": 800},
    "nolint": {},
    "functions_over_gocognit_15": 0,
    "gocognit_ceiling": [],
    "files_over_500_lines": 0,
    "file_ceiling": [],
    "coverage": {"tolerance_basis_points": 50, "floor_basis_points": 6000, "packages": {}},
}


def go_file(*functions):
    """A package with the named functions; each complexity comes from one sequential if per requested point."""
    lines = ["package fixture", ""]
    for name, ifs in functions:
        lines.append(f"func {name}(a bool) {{")
        lines += ["\tif a {}"] * ifs
        lines += ["}", ""]
    return "\n".join(lines)


def padded(lines, name):
    """A valid file of exactly lines physical lines, so the 500 and 800 limits can be crossed without comments being
    skipped."""
    head = ["package fixture", "", f"func {name}() {{}}", ""]
    return "\n".join(head + ["// padding"] * (lines - len(head))) + "\n"


def violating_file(name, lines, ifs, header=False, nolint=False):
    """A generated-looking or test file that would break every count if it were measured."""
    body = ["package fixture", ""]
    if nolint:
        body.append("//nolint:gosec // fixture")
    body += [f"func {name}(a bool) {{"]
    body += ["\tif a {}"] * ifs
    body += ["}", ""]
    body += ["// padding"] * (lines - len(body))
    text = "\n".join(body) + "\n"
    if header:
        text = "// Code generated by fixture. DO NOT EDIT.\n\n" + text
    return text


class Fixture:
    def __init__(self, directory):
        self.root = Path(directory)
        (self.root / ".github").mkdir(parents=True)

    def write(self, name, text):
        path = self.root / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")

    def baseline(self, **overrides):
        data = dict(ZERO)
        data.update(overrides)
        self.write(".github/quality-baseline.json", json.dumps(data))

    def coverage(self, package="pkg", covered=1, total=2, extra_blocks=()):
        """A hand-written package and a cover profile with one statement per block, plus any generated blocks."""
        name = package.rsplit("/", 1)[-1]
        self.write("go.mod", "module fixture\n\ngo 1.27.3\n")
        self.write(f"{package}/source.go", f"package {name}\n\nfunc Hand() {{}}\n")
        blocks = [f"fixture/{package}/source.go:{index + 1}.1,{index + 1}.2 1 {1 if index < covered else 0}"
                  for index in range(total)]
        self.write("coverage.out", "\n".join(["mode: set", *blocks, *extra_blocks]) + "\n")

    def profile(self):
        return str(self.root / "coverage.out")

    def baseline_data(self):
        return json.loads((self.root / ".github" / "quality-baseline.json").read_text(encoding="utf-8"))

    def git(self, *args):
        return subprocess.run(["git", "-C", str(self.root), *args],
                              capture_output=True, text=True, encoding="utf-8", check=True)

    def commit(self, message="base"):
        self.git("init")
        self.git("add", ".")
        self.git("-c", "user.name=fixture", "-c", "user.email=fixture@example.com",
                 "commit", "--no-gpg-sign", "-m", message)
        return self.git("rev-parse", "HEAD").stdout.strip()

    def run(self, *args):
        environment = dict(os.environ)
        environment.pop("BASE", None)
        return subprocess.run([sys.executable, str(SCRIPT), "--root", str(self.root), *args],
                              capture_output=True, text=True, encoding="utf-8", env=environment)


class CoverageTest(unittest.TestCase):
    def test_a_fall_beyond_the_tolerance_fails_and_one_at_it_passes(self):
        with tempfile.TemporaryDirectory() as directory:
            fixture = Fixture(directory)
            fixture.coverage(covered=2, total=5)
            fixture.baseline(coverage={"tolerance_basis_points": 50, "floor_basis_points": 6000,
                                       "packages": {"fixture/pkg": 5000}})

            run = fixture.run("--coverage", fixture.profile())

            self.assertEqual(run.returncode, 1, run.stderr)
            self.assertIn("coverage of fixture/pkg fell from 50.00% to 40.00% (tolerance 0.50%)", run.stderr)

            fixture.coverage(covered=99, total=200)
            run = fixture.run("--coverage", fixture.profile())

            self.assertEqual(run.returncode, 0, run.stderr)

    def test_a_rise_beyond_the_tolerance_must_raise_the_baseline(self):
        with tempfile.TemporaryDirectory() as directory:
            fixture = Fixture(directory)
            fixture.coverage(covered=3, total=5)
            fixture.baseline(coverage={"tolerance_basis_points": 50, "floor_basis_points": 6000,
                                       "packages": {"fixture/pkg": 4000}})

            run = fixture.run("--coverage", fixture.profile())

            self.assertEqual(run.returncode, 1, run.stderr)
            self.assertIn("coverage of fixture/pkg rose from 40.00% to 60.00%; raise its baseline", run.stderr)

            lowered = fixture.run("--coverage", fixture.profile(), "--write-baseline")

            self.assertEqual(lowered.returncode, 0, lowered.stderr)
            self.assertEqual(fixture.baseline_data()["coverage"]["packages"], {"fixture/pkg": 6000})
            self.assertEqual(fixture.run("--coverage", fixture.profile()).returncode, 0)

            fixture.coverage(covered=101, total=200)
            fixture.baseline(coverage={"tolerance_basis_points": 50, "floor_basis_points": 6000,
                                       "packages": {"fixture/pkg": 5000}})

            self.assertEqual(fixture.run("--coverage", fixture.profile()).returncode, 0)

    def test_a_new_package_must_start_at_the_floor(self):
        with tempfile.TemporaryDirectory() as directory:
            fixture = Fixture(directory)
            fixture.coverage(covered=2, total=5)
            fixture.baseline()

            run = fixture.run("--coverage", fixture.profile())

            self.assertEqual(run.returncode, 1, run.stderr)
            self.assertIn("new package fixture/pkg is at 40.00%, below the 60.00% floor", run.stderr)

            refused = fixture.run("--coverage", fixture.profile(), "--write-baseline")

            self.assertEqual(refused.returncode, 1, refused.stderr)
            self.assertEqual(fixture.baseline_data()["coverage"]["packages"], {})

            fixture.coverage(covered=3, total=5)
            written = fixture.run("--coverage", fixture.profile(), "--write-baseline")

            self.assertEqual(written.returncode, 0, written.stderr)
            self.assertEqual(fixture.baseline_data()["coverage"]["packages"], {"fixture/pkg": 6000})

    def test_a_package_with_code_and_no_tests_is_zero(self):
        with tempfile.TemporaryDirectory() as directory:
            fixture = Fixture(directory)
            fixture.coverage(package="other", covered=1, total=1)
            fixture.write("pkg/source.go", "package pkg\n\nfunc Hand() {}\n")
            fixture.baseline()

            run = fixture.run("--coverage", fixture.profile())

            self.assertEqual(run.returncode, 1, run.stderr)
            self.assertIn("new package fixture/pkg is at 0.00%, below the 60.00% floor", run.stderr)

    def test_generated_code_is_dropped_from_both_sides(self):
        with tempfile.TemporaryDirectory() as directory:
            fixture = Fixture(directory)
            fixture.write("pkg/generated.gen.go", "package pkg\n\nfunc Generated() {}\n")
            fixture.write("pkg/header.go",
                          "// Code generated by fixture. DO NOT EDIT.\n\npackage pkg\n\nfunc Header() {}\n")
            extra = [f"fixture/pkg/generated.gen.go:{index}.1,{index}.2 1 0" for index in range(1, 11)]
            extra += [f"fixture/pkg/header.go:{index}.1,{index}.2 1 1" for index in range(1, 6)]
            fixture.coverage(covered=1, total=2, extra_blocks=extra)
            fixture.baseline(coverage={"tolerance_basis_points": 50, "floor_basis_points": 6000,
                                       "packages": {"fixture/pkg": 5000}})

            run = fixture.run("--coverage", fixture.profile())

            self.assertEqual(run.returncode, 0, run.stderr)
            self.assertIn("coverage measured for 1 packages", run.stdout)


class CoverageBaseTest(unittest.TestCase):
    def test_a_coverage_fall_against_the_base_fails_even_if_the_branch_lowers_the_baseline(self):
        with tempfile.TemporaryDirectory() as directory:
            fixture = Fixture(directory)
            fixture.coverage(covered=4, total=5)
            fixture.baseline(coverage={"tolerance_basis_points": 50, "floor_basis_points": 6000,
                                       "packages": {"fixture/pkg": 8000}})
            base = fixture.commit()

            fixture.coverage(covered=2, total=5)
            fixture.baseline(coverage={"tolerance_basis_points": 50, "floor_basis_points": 6000,
                                       "packages": {"fixture/pkg": 4000}})

            run = fixture.run("--coverage", fixture.profile(), "--base", base)

            self.assertEqual(run.returncode, 1, run.stderr)
            self.assertIn("base baseline: coverage of fixture/pkg fell from 80.00% to 40.00%", run.stderr)

            refused = fixture.run("--coverage", fixture.profile(), "--base", base, "--write-baseline")

            self.assertEqual(refused.returncode, 1, refused.stderr)
            self.assertEqual(fixture.baseline_data()["coverage"]["packages"], {"fixture/pkg": 4000})

    def test_a_new_package_below_the_floor_against_the_base_fails(self):
        with tempfile.TemporaryDirectory() as directory:
            fixture = Fixture(directory)
            fixture.write("go.mod", "module fixture\n\ngo 1.27.3\n")
            fixture.write("pkg/source.go", "package pkg\n\nfunc Hand() {}\n")
            fixture.baseline(coverage={"tolerance_basis_points": 50, "floor_basis_points": 6000, "packages": {}})
            base = fixture.commit()

            fixture.coverage(covered=2, total=5)
            fixture.baseline(coverage={"tolerance_basis_points": 50, "floor_basis_points": 6000,
                                       "packages": {"fixture/pkg": 4000}})

            run = fixture.run("--coverage", fixture.profile(), "--base", base)

            self.assertEqual(run.returncode, 1, run.stderr)
            self.assertIn("base baseline: new package fixture/pkg is at 40.00%, below the 60.00% floor", run.stderr)

    def test_a_version_one_base_has_no_coverage_to_compare(self):
        with tempfile.TemporaryDirectory() as directory:
            fixture = Fixture(directory)
            version_one = {key: value for key, value in ZERO.items() if key != "coverage"}
            version_one["version"] = 1
            fixture.write(".github/quality-baseline.json", json.dumps(version_one))
            base = fixture.commit()

            fixture.coverage(covered=1, total=2)
            fixture.baseline(coverage={"tolerance_basis_points": 50, "floor_basis_points": 6000,
                                       "packages": {"fixture/pkg": 5000}})

            run = fixture.run("--coverage", fixture.profile(), "--base", base)

            self.assertEqual(run.returncode, 0, run.stderr)


class GrowsTest(unittest.TestCase):
    def test_each_count_and_ceiling_growth_fails_and_is_named(self):
        with tempfile.TemporaryDirectory() as directory:
            fixture = Fixture(directory)
            fixture.baseline()
            fixture.write("nolint.go", "package fixture\n\nvar _ = 0 //nolint:gosec // fixture\n")
            fixture.write("complex.go", go_file(("over15", 16), ("big", 31)))
            fixture.write("long.go", padded(501, "long"))
            fixture.write("huge.go", padded(801, "huge"))

            run = fixture.run()

            self.assertEqual(run.returncode, 1, run.stderr)
            for message in (
                "nolint:gosec grew from 0 to 1",
                "functions over gocognit 15 grew from 0 to 2",
                "files over 500 lines grew from 0 to 2",
                "new function over the cognitive-complexity ceiling 30: complex.go:big (31)",
                "new file over the 800-line ceiling: huge.go (801)",
            ):
                self.assertIn(message, run.stderr)


class FallsTest(unittest.TestCase):
    def test_a_fall_without_lowering_the_baseline_fails(self):
        with tempfile.TemporaryDirectory() as directory:
            fixture = Fixture(directory)
            fixture.baseline(
                nolint={"gosec": 1},
                functions_over_gocognit_15=2,
                gocognit_ceiling=[{"function": "complex.go:big", "complexity": 31}],
                files_over_500_lines=2,
                file_ceiling=[{"file": "huge.go", "lines": 801}],
            )
            fixture.write("clean.go", go_file(("small", 1)))

            run = fixture.run()

            self.assertEqual(run.returncode, 1, run.stderr)
            for message in (
                "nolint:gosec fell from 1 to 0",
                "functions over gocognit 15 fell from 2 to 0",
                "function complex.go:big is no longer over the cognitive-complexity ceiling 30; remove it from the baseline",
                "files over 500 lines fell from 2 to 0",
                "file huge.go is no longer over the 800-line ceiling; remove it from the baseline",
            ):
                self.assertIn(message, run.stderr)

    def test_a_ceiling_entry_that_shrinks_still_above_the_ceiling_must_be_lowered(self):
        with tempfile.TemporaryDirectory() as directory:
            fixture = Fixture(directory)
            fixture.baseline(
                functions_over_gocognit_15=1,
                gocognit_ceiling=[{"function": "complex.go:big", "complexity": 40}],
            )
            fixture.write("complex.go", go_file(("big", 31)))

            run = fixture.run()

            self.assertEqual(run.returncode, 1, run.stderr)
            self.assertIn("function complex.go:big fell from 40 to 31; lower its baseline value", run.stderr)


class ExclusionTest(unittest.TestCase):
    def test_tests_testdata_and_generated_code_are_not_measured(self):
        with tempfile.TemporaryDirectory() as directory:
            fixture = Fixture(directory)
            fixture.baseline()
            fixture.write("clean.go", go_file(("small", 1)))
            fixture.write("generated.gen.go", violating_file("genBig", 801, 31, nolint=True))
            fixture.write("header.go", violating_file("headerBig", 801, 31, header=True, nolint=True))
            fixture.write("fixture_test.go", violating_file("testBig", 801, 31, nolint=True))
            fixture.write("testdata/data.go", violating_file("dataBig", 801, 31, nolint=True))

            run = fixture.run()

            self.assertEqual(run.returncode, 0, run.stderr)
            self.assertIn("0 nolint directives (0 per-linter entries) in 0 linters, 0 functions over 15, 0 files over 500 lines", run.stdout)


class WriteBaselineTest(unittest.TestCase):
    def test_write_lowers_the_baseline_but_refuses_to_raise_it(self):
        with tempfile.TemporaryDirectory() as directory:
            fixture = Fixture(directory)
            fixture.baseline(
                nolint={"gosec": 1},
                functions_over_gocognit_15=1,
                gocognit_ceiling=[{"function": "complex.go:big", "complexity": 31}],
                files_over_500_lines=1,
                file_ceiling=[{"file": "huge.go", "lines": 801}],
            )
            fixture.write("clean.go", go_file(("small", 1)))

            lowered = fixture.run("--write-baseline")

            self.assertEqual(lowered.returncode, 0, lowered.stderr)
            data = fixture.baseline_data()
            self.assertEqual(data["nolint"], {})
            self.assertEqual(data["functions_over_gocognit_15"], 0)
            self.assertEqual(data["gocognit_ceiling"], [])
            self.assertEqual(data["files_over_500_lines"], 0)
            self.assertEqual(data["file_ceiling"], [])
            self.assertEqual(fixture.run().returncode, 0)

            fixture.write("nolint.go", "package fixture\n\nvar _ = 0 //nolint:gosec // fixture\n")
            raised = fixture.run("--write-baseline")

            self.assertEqual(raised.returncode, 1)
            self.assertIn("nolint:gosec grew from 0 to 1", raised.stderr)
            self.assertEqual(fixture.baseline_data()["nolint"], {})

    def test_write_without_coverage_keeps_the_recorded_packages(self):
        with tempfile.TemporaryDirectory() as directory:
            fixture = Fixture(directory)
            fixture.coverage(covered=1, total=2)
            fixture.baseline(
                nolint={"gosec": 1},
                coverage={"tolerance_basis_points": 50, "floor_basis_points": 6000,
                          "packages": {"fixture/pkg": 5000}},
            )

            lowered = fixture.run("--write-baseline")

            self.assertEqual(lowered.returncode, 0, lowered.stderr)
            data = fixture.baseline_data()
            self.assertEqual(data["nolint"], {})
            self.assertEqual(data["coverage"]["packages"], {"fixture/pkg": 5000})
            self.assertEqual(data["coverage"]["tolerance_basis_points"], 50)
            self.assertEqual(data["coverage"]["floor_basis_points"], 6000)



class BaseTest(unittest.TestCase):
    def test_code_and_baseline_growing_together_fails(self):
        with tempfile.TemporaryDirectory() as directory:
            fixture = Fixture(directory)
            fixture.baseline()
            fixture.write("clean.go", go_file(("small", 1)))
            base = fixture.commit()

            fixture.write("nolint.go", "package fixture\n\nvar _ = 0 //nolint:gosec // fixture\n")
            fixture.write("complex.go", go_file(("big", 31)))
            fixture.baseline(
                nolint={"gosec": 1},
                functions_over_gocognit_15=1,
                gocognit_ceiling=[{"function": "complex.go:big", "complexity": 31}],
            )

            run = fixture.run("--base", base)

            self.assertEqual(run.returncode, 1, run.stderr)
            self.assertIn("base baseline: nolint:gosec grew from 0 to 1", run.stderr)
            self.assertIn("base baseline: functions over gocognit 15 grew from 0 to 1", run.stderr)
            self.assertIn("base baseline: new function over the cognitive-complexity ceiling 30: complex.go:big (31)",
                          run.stderr)

            refused = fixture.run("--base", base, "--write-baseline")

            self.assertEqual(refused.returncode, 1, refused.stderr)
            self.assertIn("base baseline: nolint:gosec grew from 0 to 1", refused.stderr)
            self.assertEqual(fixture.baseline_data()["nolint"]["gosec"], 1)

    def test_a_base_ceiling_value_raised_with_the_baseline_fails(self):
        with tempfile.TemporaryDirectory() as directory:
            fixture = Fixture(directory)
            fixture.baseline(
                functions_over_gocognit_15=1,
                gocognit_ceiling=[{"function": "complex.go:big", "complexity": 31}],
            )
            fixture.write("complex.go", go_file(("big", 31)))
            base = fixture.commit()

            fixture.write("complex.go", go_file(("big", 32)))
            fixture.baseline(
                functions_over_gocognit_15=1,
                gocognit_ceiling=[{"function": "complex.go:big", "complexity": 32}],
            )

            run = fixture.run("--base", base)

            self.assertEqual(run.returncode, 1, run.stderr)
            self.assertIn("base baseline: function complex.go:big grew from 31 to 32", run.stderr)

    def test_first_introduction_has_no_base_baseline(self):
        with tempfile.TemporaryDirectory() as directory:
            fixture = Fixture(directory)
            fixture.write("clean.go", go_file(("small", 1)))
            base = fixture.commit()
            fixture.baseline()

            run = fixture.run("--base", base)

            self.assertEqual(run.returncode, 0, run.stderr)
            self.assertIn("has no baseline; treating this as its first introduction", run.stdout)


if __name__ == "__main__":
    unittest.main()
