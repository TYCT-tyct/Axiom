import unittest
from pathlib import Path

import justrepo

HEADER = "// Code generated by hand. DO NOT EDIT.\n\npackage plant\n"
REWRITE = "git show HEAD:{0} > {0}"  # a generator that writes back what is committed


def generated(committed, generator="", local=None, look_at=()):
    """Run the real `just generated` with `generator` (shell commands) as the generation step, in a fresh repository
    holding `committed` ({path: content}), then `local` written over it uncommitted. Returns the result and the
    contents ({path: text or None}) of the files in `look_at` afterwards."""
    with justrepo.repository() as repo:
        justrepo.commit(repo, {**committed, "gen.sh": generator + "\n"})
        justrepo.write(repo, local or {})
        result = justrepo.just(repo, "generated", "sh gen.sh")
        after = {}
        for path in look_at:
            file = Path(repo) / path
            after[path] = file.read_text(encoding="utf-8") if file.exists() else None
        return result, after


class GeneratedNames(unittest.TestCase):
    def test_headers(self):
        cases = [
            ("a generator's name", {"internal/plant/plant.gen.go": HEADER}, {}, REWRITE.format("internal/plant/plant.gen.go"),
             False),
            ("a hand-written file with the header", {"internal/plant/plant.go": HEADER}, {}, "", True),
            ("the same, new", {}, {"internal/plant/plant.go": HEADER}, "", True),
            ("the header among doc comments, as oapi-codegen writes it",
             {"internal/plant/api.go": "// Package plant.\n//\n// Code generated by x v1 DO NOT EDIT.\npackage plant\n"}, {}, "",
             True),
            ("a test file with the header", {"internal/plant/plant_test.go": HEADER}, {}, "", True),
            ("a header with Windows line ends",
             {"internal/plant/plant.go": "// Code generated by hand. DO NOT EDIT.\r\n\r\npackage plant\r\n"}, {}, "", True),
            ("an indented header, which the Go parser reads",
             {"internal/plant/plant.go": "    // Code generated by hand. DO NOT EDIT.\n\npackage plant\n"}, {}, "", True),
            ("a header indented with a tab",
             {"internal/plant/plant.go": "\t// Code generated by hand. DO NOT EDIT.\n\npackage plant\n"}, {}, "", True),
            ("a header after a block comment on its line",
             {"internal/plant/plant.go": "/* x */ // Code generated by hand. DO NOT EDIT.\npackage plant\n"}, {}, "", True),
            ("a header without the do-not-edit mark",
             {"internal/plant/plant.go": "// Code generated by hand.\n\npackage plant\n"}, {}, "", False),
            ("a header in another case, which golangci-lint does not read",
             {"internal/plant/plant.go": "// code generated by hand. do not edit.\n\npackage plant\n"}, {}, "", False),
            ("the words in a trailing comment",
             {"internal/plant/plant.go": "package plant\n\nvar x = 1 // Code generated by hand. DO NOT EDIT.\n"}, {}, "",
             False),
            ("other file types", {"docs/plant.md": HEADER}, {}, "", False),
        ]
        for name, committed, local, generator, fails in cases:
            with self.subTest(name):
                result, _ = generated(committed, generator, local)
                self.assertEqual(result.returncode != 0, fails, result.stdout)
                if fails:
                    self.assertIn("only generated files carry the generated-code header", result.stdout)

    def test_a_generator_that_names_its_output_wrong_fails(self):
        """The check runs after generation too: this output did not exist before it."""
        result, _ = generated({}, r"printf '// Code generated by x. DO NOT EDIT.\n\npackage plant\n' > db.go")
        self.assertNotEqual(result.returncode, 0, result.stdout)
        self.assertIn("db.go", result.stdout)

    def test_generated_files_must_match_what_the_generator_writes(self):
        path = "internal/plant/plant.gen.go"
        cases = [
            ("unchanged", {path: HEADER}, REWRITE.format(path), False),
            ("stale", {path: HEADER}, f"echo '// changed' >> {path}", True),
            ("a new file the generator writes, not committed", {}, f"cp /dev/null {path}", True),
            ("a hand-written file the generator does not write", {path: HEADER}, "", True),
            ("a generator that fails", {path: HEADER}, "exit 1", True),
        ]
        for name, committed, generator, fails in cases:
            with self.subTest(name):
                result, _ = generated(committed, generator)
                self.assertEqual(result.returncode != 0, fails, result.stdout)

    def test_deleted_files_are_listed(self):
        result, _ = generated({"web/forged.gen.ts": "export const x = 1;\n"})
        self.assertNotEqual(result.returncode, 0, result.stdout)
        self.assertIn(" D web/forged.gen.ts", result.stdout)

    def test_a_name_git_would_quote_is_deleted_too(self):
        """git ls-files prints non-ASCII names in quotes unless told to use NUL separators."""
        result, _ = generated({"internal/plant/forgé.gen.go": HEADER})
        self.assertNotEqual(result.returncode, 0, result.stdout)
        self.assertIn(" D", result.stdout)

    def test_uncommitted_generated_files_are_refused_not_deleted(self):
        path = "internal/plant/plant.gen.go"
        cases = [
            ("an untracked file", {}, {path: HEADER}),
            ("a modified file", {path: HEADER}, {path: HEADER + "// edited\n"}),
        ]
        for name, committed, local in cases:
            with self.subTest(name):
                result, after = generated(committed, REWRITE.format(path), local, look_at=[path])
                self.assertNotEqual(result.returncode, 0, result.stdout)
                self.assertIn(path, result.stdout)
                self.assertEqual(after[path], local[path])

    def test_a_git_failure_fails(self):
        self.assertNotEqual(justrepo.just_with_broken_git("generated", "true").returncode, 0)


if __name__ == "__main__":
    unittest.main()
